export type Box = [number, number, number, number];

// The box at time t: straight-line between the two nearest keys, held still
// before the first and after the last.
export function boxAt(track: Track, t: number): Box {
  const keys = track.keys;
  if (t <= keys[0][0]) return keys[0].slice(1) as Box;
  const last = keys[keys.length - 1];
  if (t >= last[0]) return last.slice(1) as Box;
  let i = 1;
  while (keys[i][0] < t) i++;
  const a = keys[i - 1];
  const b = keys[i];
  const u = (t - a[0]) / (b[0] - a[0]);
  return [1, 2, 3, 4].map((k) => a[k] + (b[k] - a[k]) * u) as Box;
}
